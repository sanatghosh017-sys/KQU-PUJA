export function numberToWordsIndian(n: number): string {
  if (n === 0) return 'Zero';
  const ones = [
    '', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine',
    'Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen',
    'Seventeen', 'Eighteen', 'Nineteen'
  ];
  const tens = [
    '', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'
  ];

  function helper(num: number): string {
    let str = '';
    if (num > 99) {
      str += ones[Math.floor(num / 100)] + ' Hundred ';
      num %= 100;
    }
    if (num > 19) {
      str += tens[Math.floor(num / 10)] + ' ' + ones[num % 10];
    } else if (num > 0) {
      str += ones[num];
    }
    return str.trim();
  }

  let crore = Math.floor(n / 10000000);
  n %= 10000000;
  let lakh = Math.floor(n / 100000);
  n %= 100000;
  let thousand = Math.floor(n / 1000);
  n %= 1000;
  let remainder = n;

  let result = '';
  if (crore > 0) result += helper(crore) + ' Crore ';
  if (lakh > 0) result += helper(lakh) + ' Lakh ';
  if (thousand > 0) result += helper(thousand) + ' Thousand ';
  if (remainder > 0) result += helper(remainder);

  return result.trim() + ' Rupees Only';
}

export const getWebsiteHttpsUrl = (): string => {
  if (typeof window !== 'undefined' && window.location) {
    if (window.location.protocol === 'https:') {
      return `${window.location.origin}${window.location.pathname === '/' ? '' : window.location.pathname}`;
    } else if (window.location.host) {
      return `https://${window.location.host}${window.location.pathname === '/' ? '' : window.location.pathname}`;
    }
  }
  return COMMITTEE_INFO.websiteUrl;
};

